import { expect, test } from "@playwright/test";
import { createHash, randomUUID } from "node:crypto";
import { readFile } from "node:fs/promises";

test("Owner downloads a complete selected business file without changing source or exposing private configuration", async ({page}) => {
  test.setTimeout(90_000);
  const password = process.env.ACO_TEST_DEMO_PASSWORD;
  if (!password) throw Error("Explicit synthetic browser password required");
  await page.goto("/login");
  await page.getByRole("link", {name:"Sign in",exact:true}).click();
  await page.getByLabel("Username or email").fill("owner@example.test");
  await page.getByLabel("Password",{exact:true}).fill(password);
  await page.getByRole("button",{name:"Sign In",exact:true}).click();
  await expect(page).toHaveURL(/\/onboarding$/);
  await page.getByLabel("Workspace name",{exact:true}).fill(`Export ${randomUUID()}`);
  await page.getByLabel("Timezone",{exact:true}).fill("UTC");
  const creating=page.waitForResponse(r=>new URL(r.url()).pathname==="/api/workspaces"&&r.request().method()==="POST");
  await page.getByRole("button",{name:"Create demo workspace",exact:true}).click();
  const created=await creating;expect(created.status()).toBe(201);
  const workspace=(await created.json()).id,base=`/api/workspaces/${workspace}`;
  const source=page.getByRole("region",{name:"Synthetic accounting setup",exact:true});
  const importing=page.waitForResponse(r=>new URL(r.url()).pathname===base+"/demo/accounting/seed"&&r.request().method()==="POST");
  await source.getByRole("button",{name:"Import synthetic demo data",exact:true}).click();
  expect((await importing).status()).toBe(201);
  await expect(source).toContainText("24 imported invoices · 6 imported customers");
  const before=await (await page.request.get(base+"/receivables?page_size=100")).json();
  const panel=page.getByRole("region",{name:"Business export",exact:true});
  await expect(panel.getByRole("checkbox")).toHaveCount(16);
  await expect(panel).toContainText("separately authorized private downloads");
  const downloading=page.waitForEvent("download"), exporting=page.waitForResponse(r=>new URL(r.url()).pathname===base+"/exports");
  await panel.getByRole("button",{name:"Download business export",exact:true}).click();
  const response=await exporting;expect(response.status()).toBe(200);
  expect(response.request().headers()["x-csrf-token"]).toBeTruthy();
  const download=await downloading,path=await download.path();expect(path).not.toBeNull();
  const bytes=await readFile(path!);const file=JSON.parse(bytes.toString());
  expect(download.suggestedFilename()).toBe(`aco-business-${workspace}.json`);
  expect(file.tenant_id).toBe(workspace);expect(file.counts.invoices).toBe(24);expect(file.counts.customers).toBe(6);
  expect(file.selection.resources).toHaveLength(16);expect(file.raw_originals_included).toBe(false);
  expect(file.records.invoices.every((row:{synthetic:boolean;balance_minor:unknown})=>row.synthetic&&typeof row.balance_minor==="string")).toBe(true);
  expect(createHash("sha256").update(bytes).digest("hex")).toBe(response.headers()["x-content-sha256"]);
  expect(bytes.toString()).not.toMatch(/encrypted_credentials_ref|encrypted_token|object_key|signed_url/);
  const after=await (await page.request.get(base+"/receivables?page_size=100")).json();
  // Request-time as_of_at changes; every returned financial record must remain exact.
  expect(after.items).toEqual(before.items);
  expect(after.total).toEqual(before.total);
  await expect(panel.getByRole("status")).toContainText("Download prepared");
  await page.reload();await page.getByLabel("Workspace",{exact:true}).selectOption(workspace);
  await expect(panel.getByRole("status")).toHaveCount(0);
  await page.setViewportSize({width:390,height:844});
  await expect(panel.getByRole("button",{name:"Download business export",exact:true})).toBeVisible();
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true);
});
