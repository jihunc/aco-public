import {expect, test} from '@playwright/test';
import {readFileSync, existsSync} from 'node:fs';
const env = Object.fromEntries((existsSync('.env') ? readFileSync('.env', 'utf8') : '').split('\n').filter(x=>x.includes('=')).map(x=>[x.slice(0,x.indexOf('=')),x.slice(x.indexOf('=')+1)]));
const password = process.env.ACO_TEST_DEMO_PASSWORD || env.DEMO_PASSWORD;
test('real identity login, persisted safe workspace and sign out', async ({page})=>{
  await page.goto('/login');
  await page.getByRole('link', {name:'Sign in'}).click();
  await page.getByLabel('Username or email').fill('owner@example.test');
  await page.getByLabel('Password', {exact:true}).fill(password);
  await page.getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(page).toHaveURL(/\/onboarding$/);
  expect((await page.request.get('/api/me')).status()).toBe(200);
  const name = `Synthetic browser ${Date.now()}`;
  await page.getByLabel('Workspace name').fill(name);
  await page.getByLabel('Timezone',{exact:true}).fill('Australia/Melbourne');
  await page.getByRole('button',{name:'Create demo workspace'}).click();
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible();
  await expect(page.getByText('Outbound paused · Automation off')).toBeVisible();
  await page.reload();
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible();
  expect(page.url()).not.toMatch(/token|code=|state=/);
  const me = await page.request.get('/api/me');
  const info = await me.json();
  const denial = await page.request.get('/api/workspaces/00000000-0000-0000-0000-000000000001');
  expect(denial.status()).toBe(403);
  expect(info.workspaces.some((w: {name:string})=>w.name===name)).toBe(true);
  await page.getByRole('button',{name:'Sign out'}).click();
  await expect(page).toHaveURL(/\/login$/);
  expect((await page.request.get('/api/me')).status()).toBe(401);
});

test('registration, two real identities, guarded join and viewer denial', async ({browser})=>{
  const creator=await browser.newContext();
  const page=await creator.newPage();
  await page.goto('http://127.0.0.1:53000/login');
  await page.getByRole('link',{name:'Sign in',exact:true}).click();
  await page.getByRole('link',{name:'Register'}).click();
  const email=`signup-${Date.now()}@example.test`;
  await page.getByRole('textbox',{name:'Username',exact:true}).fill(email);
  await page.getByRole('textbox',{name:'Email',exact:true}).fill(email);
  await page.getByRole('textbox',{name:'First name',exact:true}).fill('Synthetic');
  await page.getByRole('textbox',{name:'Last name',exact:true}).fill('Registrant');
  await page.getByRole('textbox',{name:'Password',exact:true}).fill(password);
  await page.getByRole('textbox',{name:'Confirm password',exact:true}).fill(password);
  await page.getByRole('button',{name:'Register',exact:true}).click();
  await expect(page).toHaveURL(/\/onboarding$/);
  const name=`Signup tenant ${Date.now()}`;
  await page.getByLabel('Workspace name',{exact:true}).fill(name);
  await page.getByRole('button',{name:'Create demo workspace'}).click();
  await expect(page.getByRole('heading',{name,exact:true})).toBeVisible();
  const created=await (await page.request.get('http://127.0.0.1:53000/api/me')).json();
  const tenant=created.workspaces[0].id;
  await page.getByLabel('Teammate email').fill('owner@example.test');
  await page.getByRole('button',{name:'Create invitation'}).click();
  const code=await page.getByLabel('Invitation code').inputValue();
  const member=await browser.newContext();
  const memberPage=await member.newPage();
  await memberPage.goto('http://127.0.0.1:53000/login');
  await memberPage.getByRole('link',{name:'Sign in',exact:true}).click();
  await memberPage.getByLabel('Username or email').fill('owner@example.test');
  await memberPage.getByLabel('Password',{exact:true}).fill(password);
  await memberPage.getByRole('button',{name:'Sign In',exact:true}).click();
  await expect(memberPage).toHaveURL(/\/onboarding$/);
  const base='http://127.0.0.1:53000';
  expect((await memberPage.request.get(`${base}/api/workspaces/${tenant}`)).status()).toBe(403);
  const ownerMe=await (await memberPage.request.get(`${base}/api/me`)).json();
  if(ownerMe.workspaces.length){
    expect((await page.request.get(`${base}/api/workspaces/${ownerMe.workspaces[0].id}`)).status()).toBe(403);
  }
  await memberPage.getByLabel('Join code').fill(code);
  await memberPage.getByRole('button',{name:'Accept invitation'}).click();
  await expect(memberPage.getByRole('heading',{name,exact:true})).toBeVisible();
  await expect(memberPage.getByText('Australia/Melbourne · viewer')).toBeVisible();
  await expect(memberPage.getByRole('button',{name:'Create invitation'})).toHaveCount(0);
  const viewerMe=await (await memberPage.request.get(`${base}/api/me`)).json();
  const headers={origin:base,'x-csrf-token':viewerMe.csrf_token};
  expect((await memberPage.request.patch(`${base}/api/workspaces/${tenant}?role=owner`,{headers,data:{name:'forged',timezone:'UTC'}})).status()).toBe(403);
  const oldCookie=(await member.cookies()).find(c=>c.name==='aco_session')!;
  const refreshed=await memberPage.request.post(`${base}/api/auth/refresh`,{headers,data:{}});
  expect(refreshed.status()).toBe(200);
  expect((await member.cookies()).find(c=>c.name==='aco_session')!.value).not.toBe(oldCookie.value);
  expect((await memberPage.request.get(`${base}/api/me`,{headers:{cookie:`aco_session=${oldCookie.value}`}})).status()).toBe(401);
  expect((await memberPage.request.get(`${base}/api/me`)).status()).toBe(200);
  await creator.close();await member.close();
});

